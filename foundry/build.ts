/** Dev host sheet, the shared ship styles, the editor sheet, and the actor sheet. */
const host = await Deno.readTextFile(new URL("../dev/host.css", import.meta.url));
const ship = await Deno.readTextFile(new URL("../styles.css", import.meta.url));
const editor = await Deno.readTextFile(new URL("./editor.css", import.meta.url));
const actor = await Deno.readTextFile(new URL("./actor.css", import.meta.url));

/** Inserts the closing brace that belongs before .design-list. */
const repaired = ship.replace(
  "  border-radius: 6px;\n\n.design-list",
  "  border-radius: 6px;\n}\n\n.design-list"
);

/** Nests the dev host sheet under .blueprint-mount and shortens the page height for the actor sheet. */
const scopedHost = host
  .replaceAll(":root", "&")
  .replaceAll("\nbody {", "\n& {")
  .replaceAll("min-height: 100dvh;", "min-height: 36rem;");

/** Stylesheet text written to foundry/styles/blueprint.css. */
const css = `/* Generated by foundry/build.ts. Edit dev/host.css, styles.css, foundry/editor.css, and foundry/actor.css, then run deno task foundry. */\n.blueprint-mount {\n${scopedHost}\n${repaired}\n${editor}\n}\n${actor}`;

await Deno.mkdir(new URL("./styles/", import.meta.url), { recursive: true });
await Deno.writeTextFile(new URL("./styles/blueprint.css", import.meta.url), css);

const config = fileUrl("./bundle.json");
const preact = fileUrl("./dist/preact.js");
const blueprint = fileUrl("./dist/blueprint.js");
await run("deno", [
  "bundle",
  "--config",
  config,
  "--platform",
  "browser",
  "--minify",
  fileUrl("./src/preact.ts"),
  "-o",
  preact
]);
await run("deno", [
  "bundle",
  "--config",
  config,
  "--platform",
  "browser",
  "--minify",
  "--external=preact",
  "--external=preact/hooks",
  "--external=preact/jsx-runtime",
  fileUrl("./src/host.tsx"),
  "-o",
  blueprint
]);

let source = await Deno.readTextFile(blueprint);
// The bundle must import Preact from the sibling file this module ships.
// Accepts `from"preact"` and `from "preact"`. Longer specifiers are rewritten first.
for (const specifier of ["preact/jsx-runtime", "preact/hooks", "preact"]) {
  const forms = [`from"${specifier}"`, `from "${specifier}"`];
  if (!forms.some((form) => source.includes(form))) {
    throw new Error(`blueprint.js is missing an import from ${specifier}`);
  }
  for (const form of forms) source = source.replaceAll(form, 'from "./preact.js"');
}
if (source.includes('from"preact') || source.includes('from "preact')) {
  throw new Error("blueprint.js still imports Preact from a bare specifier");
}
await Deno.writeTextFile(blueprint, source);

/** Filesystem path for a URL relative to this build script. */
function fileUrl(path: string): string {
  return new URL(path, import.meta.url).pathname;
}

/** Runs a command and prints its output. A failed command stops the build with that status. */
async function run(command: string, args: string[]): Promise<void> {
  const result = await new Deno.Command(command, { args }).output();
  const output = new TextDecoder().decode(result.stdout) +
    new TextDecoder().decode(result.stderr);
  if (output.trim()) console.log(output.trim());
  if (!result.success) Deno.exit(result.code);
}
